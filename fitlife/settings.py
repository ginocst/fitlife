def env(nombre, defecto=None):
    """Lee una variable del .env. Si es obligatoria y falta, lanza un aviso."""
    valor = os.environ.get(nombre, defecto)
    if valor is None:
        raise ImproperlyConfigured(f'Falta la variable {nombre} en el archivo .env.')
    return valor

def env_lista(nombre):
    """Lee una variable del .env que contiene varios valores separados por coma
    y la devuelve como lista de Python."""
    return [x.strip() for x in env(nombre, '').split(',') if x.strip()]

